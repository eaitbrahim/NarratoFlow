def _sample(segment: svgelements.PathSegment) -> list[tuple[float, float]]:
    length_px = float(segment.length()) * SCALE_PX
    count = max(MIN_SAMPLES, math.ceil(length_px / SAMPLE_SPACING_PX))
    points: list[tuple[float, float]] = []
    for i in range(count):
        point = segment.point(i / (count - 1))
        points.append((point.x * SCALE_PX + OFFSET_PX, point.y * SCALE_PX + OFFSET_PX))
    return points


def rasterize(paths: Sequence[str]) -> bytes:
    """An 8-bit grayscale PNG, black ink on white, of SVG path `d` strings on a 24-unit grid.

    A closed subpath ends in a Close segment, which is sampled like any other and so draws back
    to the subpath's start.
    """
    canvas = np.full((SIZE_PX, SIZE_PX), 255, dtype=np.uint8)
    for d in paths:
        for subpath in svgelements.Path(d).as_subpaths():
            points: list[tuple[float, float]] = []
            for segment in subpath:
                if not isinstance(segment, svgelements.Move):
                    points.extend(_sample(segment))
            if not points:
                continue
            line = np.rint(np.asarray(points)).astype(np.int32).reshape(-1, 1, 2)
            cv2.polylines(
                canvas, [line], isClosed=False, color=0, thickness=STROKE_PX, lineType=cv2.LINE_AA
            )
    ok, encoded = cv2.imencode(".png", canvas)
    if not ok:
        raise ValueError("PNG encoding failed")
    return bytes(encoded.tobytes())


def _icon_paths(name: str, nodes: dict[str, object]) -> tuple[list[str], str | None]:
    entry = nodes.get(name)
    if not isinstance(entry, list) or not entry:
        return [], "not in the outline nodes JSON"
    paths: list[str] = []
    for node in entry:
        if (
            not isinstance(node, list)
            or len(node) != 2
            or node[0] != "path"
            or not isinstance(node[1], dict)
        ):
            return [], f"has a node that is not a plain path: {node!r}"
        attrs = node[1]
        if set(attrs) != {"d"} or not isinstance(attrs["d"], str):
            return [], f"has a path with attributes {sorted(attrs)}, only d is allowed"
        paths.append(attrs["d"])
    return paths, None


def _check_png(png: bytes) -> str | None:
    try:
        ink = binarize(png)
        report = check_density(ink, line_weight_px=3.0)
        if not report.ok:
            return f"fails the density check: {report.reason}"
        if not extract_strokes(ink).strokes:
            return "yields no strokes"
    except NarratoFlowError as exc:
        return f"is refused: {exc}"
    return None


def _entry(spec: IconSpec, sha: str) -> str:
    return (
        f'[icons."{spec.obj}|generic"]\nfile = "{spec.obj}.png"\n'
        f'description = {json.dumps(spec.description)}\nlicense = "{LICENSE_ID}"\n'
        f'source = "{URL}#{SVG_PREFIX}{spec.tabler}.svg"\nsha256 = "{sha}"\n'
    )


def build_pack(data: bytes, out_dir: Path) -> str:
    """Verify the pinned tarball, rasterize every curated icon and write the PNGs and licence.

    Returns the index.toml text. Raises one ValueError listing every refused icon; nothing is
    written in that case.
    """
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        raise ValueError(f"{URL}: tarball sha256 {got} != pinned {SHA256}")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        names = set(archive.getnames())

        def read(member: str) -> bytes:
            handle = archive.extractfile(member)
            if handle is None:
                raise ValueError(f"{URL}: {member} is not a regular file")
            return handle.read()

        for member in (NODES_MEMBER, LICENSE_MEMBER):
            if member not in names:
                raise ValueError(f"{URL}: missing tarball member {member}")
        nodes = json.loads(read(NODES_MEMBER))
        license_text = read(LICENSE_MEMBER)
    failures: list[str] = []
    pngs: list[tuple[IconSpec, bytes]] = []
    for spec in ICONS:
        paths, problem = _icon_paths(spec.tabler, nodes)
        if problem is None and f"{SVG_PREFIX}{spec.tabler}.svg" not in names:
            problem = f"has no {SVG_PREFIX}{spec.tabler}.svg member"
        if problem is None:
            png = rasterize(paths)
            problem = _check_png(png)
            if problem is None:
                pngs.append((spec, png))
        if problem is not None:
            failures.append(f"{spec.tabler}: {problem}")
    if failures:
        raise ValueError("refused icons:\n" + "\n".join(failures))
    out_dir.mkdir(parents=True, exist_ok=True)
    entries: list[str] = []
    for spec, png in pngs:
        (out_dir / f"{spec.obj}.png").write_bytes(png)
        entries.append(_entry(spec, hashlib.sha256(png).hexdigest()))
    (out_dir / LICENSE_FILE).write_bytes(license_text)
    return HEADER + "\n" + "\n".join(entries)


def main() -> None:
    with urllib.request.urlopen(URL, timeout=120) as resp:
        data = resp.read()
    (OUT / "index.toml").write_text(build_pack(data, OUT), encoding="utf-8")


if __name__ == "__main__":
    main()
